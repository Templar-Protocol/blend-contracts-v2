use crate::{constants::SCALAR_12, storage::ReserveData};

// Complete finite partition of the original positive-u8 rate domain.
// Every u8 amount is explicitly checked; unwind assertions remain enabled.
fn check_rate(rate_h: u8, amount: u8) {
    assert!(rate_h >= 1);
    let amount = amount as i128;
    let b_rate = (rate_h as i128) * SCALAR_12 / 100;
    let data = ReserveData {
        d_rate: 0,
        b_rate,
        ir_mod: 0,
        b_supply: 0,
        d_supply: 0,
        backstop_credit: 0,
        last_time: 0,
    };
    let down = data.to_b_token_down(&(), amount);
    let up = data.to_b_token_up(&(), amount);
    let product = amount * SCALAR_12;
    assert_eq!(down, product / b_rate);
    assert_eq!(up, (product + b_rate - 1) / b_rate);
    assert!(down * b_rate <= product && product < (down + 1) * b_rate);
    assert!(product <= up * b_rate && (up - 1) * b_rate < product);
    assert!(up >= down && up - down <= 1);
}

macro_rules! rate_proof {
    ($name:ident, $rate:literal) => {
        #[kani::proof]
        #[kani::unwind(257)]
        fn $name() {
            let mut amount = 0u16;
            while amount < 256 {
                check_rate($rate, amount as u8);
                amount += 1;
            }
            assert_eq!(amount, 256);
            kani::cover!(amount == 256);
        }
    };
}
